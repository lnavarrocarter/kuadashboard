'use strict';

// Rebuild the review inventory for the globally guarded local API (#363).
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const sources = [
  'server.js', 'lib/consoleSessions.js', 'lib/kubeLogs/routes.js',
  ...fs.readdirSync(path.join(root, 'routes')).filter(name => name.endsWith('.js') && !name.endsWith('.test.js')).sort().map(name => `routes/${name}`),
];
const rows = [];
for (const file of sources) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  const pattern = /^[\t ]*(?:app|router)\.(post|put|patch|delete)\(\s*(['"`])([^'"`]+)\2/gm;
  for (const match of source.matchAll(pattern)) {
    const line = source.slice(0, match.index).split('\n').length;
    rows.push(`| ${match[1].toUpperCase()} | \`${match[3]}\` | [${file}](../../${file}#L${line}) |`);
  }
}

const introduction = `# Local API write inventory

Generated by \`node scripts/local-api-write-inventory.js\`. Router paths below are relative to their mount in \`server.js\`.

## Common admission policy

Every local \`/api\` write passes through \`localHostGuard\` and \`localRequestGuard\` before body parsing, provider routing or side effects. This includes settings, credentials, account operations, provider actions, queries that use POST, console tickets and plugin routes. The request's Host must be localhost, a canonical loopback IP, or the configured KUA_HOSTNAME alias. Forwarding headers have no authority.

Browser origins must be serialized HTTP(S) origins on those allowed hosts. The application accepts local development ports. Opaque, malformed, duplicate and foreign origins fail with 403. Cross-site Fetch Metadata also fails. An originless same-site browser request fails, while originless native clients and same-origin browser requests remain supported. The tests exercise form, text and JSON requests before a handler or parser can run.

All console WebSocket paths apply the same admission policy before consuming a one-use, path-bound session ticket. Console preparation additionally requires a loopback peer. Provider permissions, read-only mode, confirmations and audit checks continue inside the admitted request.

GET and HEAD routes retain their existing controls. OAuth navigation and GET callbacks use their provider-specific state checks. OPTIONS does not grant cross-origin access. This inventory records write methods and does not redefine their authorization or classify POST queries as provider mutations.

## Declared write handlers

There are ${rows.length} declared handlers in this source snapshot. Routes mounted under \`/api\` inherit the common admission policy, including handlers added after this inventory is regenerated. Additional guards such as \`X-Profile-Id\`, context confirmations, session authentication and read-only policies remain in their handlers.

| Method | Declared path | Source |
| --- | --- | --- |
`;
fs.writeFileSync(path.join(root, 'docs/architecture/local-api-write-inventory.md'), introduction + rows.join('\n') + '\n');
console.log(`Inventoried ${rows.length} write handlers.`);
